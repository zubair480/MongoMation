// Generates an I/O probe program for Developer 1 to verify a scene's Modbus mapping on the live rig.
//   npx tsx scripts/gen-probe.ts scenes/<id>.json > out/probe.st
// The probe energizes each actuator for 1 s in address order (a "walking bit"), so every conveyor, light
// and pusher in Factory I/O should move in the order listed in the scene file. Sensor inputs are mirrored
// into memory words so they can be watched on the OpenPLC monitoring page while pressing buttons.
import { readFileSync } from "node:fs";
import { SceneDefinition } from "@mongomation/types";

const scene = SceneDefinition.parse(JSON.parse(readFileSync(process.argv[2], "utf8")));
const bools = scene.tags.filter((t) => t.dataType === "BOOL");
const outs = bools.filter((t) => t.role === "actuator");
const ins = bools.filter((t) => t.role === "sensor");
const v = (i: number, p: string) => `${p}${i}`;

const decl = [
  ...ins.map((t, i) => `    ${v(i, "I")} AT ${t.plcAddress} : BOOL; (* ${t.name} *)`),
  ...outs.map((t, i) => `    ${v(i, "Q")} AT ${t.plcAddress} : BOOL; (* ${t.name} *)`),
].join("\n");
const steps = outs.map((t, i) => `  ${v(i, "Q")} := (Phase = ${i}); (* ${t.name} *)`).join("\n");

console.log(`(* I/O probe for scene ${scene.id} (${scene.factoryIoScene}). Generated by scripts/gen-probe.ts. *)
PROGRAM io_probe
  VAR
${decl}
  END_VAR
  VAR
    Tick : TON;
    Phase : INT := 0;
    InputsSeen : INT := 0;
  END_VAR
  Tick(IN := NOT Tick.Q, PT := T#1000ms);
  IF Tick.Q THEN
    Phase := Phase + 1;
    IF Phase >= ${Math.max(outs.length, 1)} THEN
      Phase := 0;
    END_IF;
  END_IF;
${steps}
  InputsSeen := 0;
${ins.map((_, i) => `  IF ${v(i, "I")} THEN InputsSeen := InputsSeen + 1; END_IF;`).join("\n")}
END_PROGRAM

CONFIGURATION Config0
  RESOURCE Res0 ON PLC
    TASK task0(INTERVAL := T#20ms, PRIORITY := 0);
    PROGRAM instance0 WITH task0 : io_probe;
  END_RESOURCE
END_CONFIGURATION`);
